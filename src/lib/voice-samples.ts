// Only type imports, so scripts/build-voice-samples.mjs can load this file directly with Node.
import type { Locale } from "./i18n/locales";

/**
 * One short narration line per language, the same scene in each so voices compare across
 * languages. Simplified Chinese has its own line because Gemini reads both scripts alike.
 */
export const VOICE_SAMPLE_TEXTS = {
  "zh-Hant": "夜色降臨，古老的城門在眾人面前緩緩開啟。",
  "zh-Hans": "烛火摇曳，旅人们围坐桌边，等待故事开始。",
  ja: "夜が更け、古い城門が人々の前でゆっくりと開いていく。",
  ko: "밤이 깊어지자, 오래된 성문이 사람들 앞에서 천천히 열리기 시작했다.",
  en: "As night falls, the ancient city gate slowly creaks open before the crowd.",
  de: "Die Nacht bricht herein, und das alte Stadttor öffnet sich langsam vor den Wartenden.",
  es: "Cae la noche, y la antigua puerta de la ciudad se abre lentamente ante todos.",
} as const satisfies Record<Locale, string>;

/** Pre-generated by scripts/build-voice-samples.mjs and served from public/. */
export function voiceSamplePath(locale: Locale, voice: string): string {
  return `/voice-samples/${locale}/${voice}.m4a`;
}

/** The pre-generated file for a request that is exactly one voice reading one sample line. */
export function voiceSampleAsset(input: {
  text: string;
  voice?: string;
  toneHint?: string;
  genreHint?: string;
}): string | undefined {
  if (input.toneHint || input.genreHint) return undefined;
  if (!input.voice || !/^[A-Za-z]+$/.test(input.voice)) return undefined;
  const entry = Object.entries(VOICE_SAMPLE_TEXTS).find(([, text]) => text === input.text);
  return entry ? voiceSamplePath(entry[0] as Locale, input.voice) : undefined;
}
